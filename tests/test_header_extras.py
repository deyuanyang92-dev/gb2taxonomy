"""Header fields beyond the source feature: COMMENT, DBLINK, structured comments, primer names."""

from io import StringIO

from Bio import SeqIO

from g2t._extract.parse import extract_metadata, parse_primers

REC = """LOCUS       OZ580602               15000 bp    DNA     circular INV 01-JAN-2026
DEFINITION  Cocytia richardi mitochondrion, complete genome.
ACCESSION   OZ580602
VERSION     OZ580602.1
DBLINK      BioProject: PRJEB129475
            BioSample: SAMEA120504105
            Sequence Read Archive: ERR17583910, ERR17591491
KEYWORDS    .
SOURCE      mitochondrion Cocytia richardi
  ORGANISM  Cocytia richardi
            Eukaryota; Metazoa; Arthropoda.
COMMENT     The assembly ilCocRich1.hap1.1 is based on 91x PacBio data and
            Arima2 Hi-C data generated by Project Psyche.
FEATURES             Location/Qualifiers
     source          1..12
                     /organism="Cocytia richardi"
                     /PCR_primers="fwd_name: LCO1490, fwd_seq: ggtcaacaaatcataaagatattgg,
                     rev_name: HC02198, rev_seq: taaacttcagggtgaccaaaaaatca;
                     fwd_name: FormCOId_FM13, fwd_seq: tgtaaaacg, rev_name: FormCOId_RM13,
                     rev_seq: caggaaac"
ORIGIN
        1 acgtacgtac gt
//
"""


def test_comment_dblink_and_primers_are_extracted():
    rec = next(SeqIO.parse(StringIO(REC), "genbank"))
    m = extract_metadata(rec, include_taxonomy=False)
    assert m["Comment"].startswith("The assembly ilCocRich1.hap1.1 is based on 91x PacBio data")
    assert (m["BioProject"], m["BioSample"], m["SRA"]) == ("PRJEB129475", "SAMEA120504105", "ERR17583910; ERR17591491")
    assert (m["primer_fwd"], m["primer_rev"]) == ("LCO1490; FormCOId_FM13", "HC02198; FormCOId_RM13")


def test_primer_names_without_sequences():
    assert parse_primers("fwd_name: its5, fwd_seq: gg, fwd_name: 5.8mussf, rev_name: its4") == {
        "primer_fwd": "its5; 5.8mussf", "primer_rev": "its4"}
