#!/usr/bin/env python3
"""Write docs/CLI_REFERENCE.md from the --help text of every g2t command, so the option reference cannot drift."""

import contextlib
import io
import sys
from pathlib import Path

from g2t import RELEASE, _cli

COMMANDS = [
    ("g2t", "main_pipeline"),
    ("g2t-download", "main_download"),
    ("g2t-extract", "main_extract"),
    ("g2t-classify", "main_classify"),
    ("g2t-voucher", "main_voucher"),
    ("g2t-reconcile", "main_reconcile"),
    ("g2t-organize", "main_organize"),
    ("g2t-curate", "main_curate"),
    ("g2t-mitostats", "main_mitostats"),
    ("g2t-cite", "main_cite"),
]

out = [
    f"# Command-line reference (g2t {RELEASE})",
    "",
    "Generated by `scripts/make_cli_reference.py` from each command's `--help`; README.md and USAGE.en.md "
    "explain the options in context.",
    "",
]
for prog, fn in COMMANDS:
    buf = io.StringIO()
    argv0, sys.argv[0] = sys.argv[0], prog  # argparse names the program after sys.argv[0]
    try:
        with contextlib.redirect_stdout(buf), contextlib.suppress(SystemExit):
            getattr(_cli, fn)(["--help"])
    finally:
        sys.argv[0] = argv0
    out += [f"## {prog}", "", "```text", buf.getvalue().rstrip(), "```", ""]
path = Path(__file__).resolve().parents[1] / "docs" / "CLI_REFERENCE.md"
path.write_text("\n".join(out), encoding="utf-8")
print(path, sum(t.count("\n  -") for t in out))
